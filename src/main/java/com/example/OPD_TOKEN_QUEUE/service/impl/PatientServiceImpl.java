package com.example.OPD_TOKEN_QUEUE.service.impl;

import com.example.OPD_TOKEN_QUEUE.model.Patient;
import com.example.OPD_TOKEN_QUEUE.repository.PatientRepository;
import com.example.OPD_TOKEN_QUEUE.service.PatientService;

import org.springframework.stereotype.Service;

import java.util.List;

@Service
public class PatientServiceImpl implements PatientService {

    private final PatientRepository patientRepository;

    public PatientServiceImpl(PatientRepository patientRepository) {
        this.patientRepository = patientRepository;
    }

    @Override
    public Patient savePatient(Patient patient) {
        return patientRepository.save(patient);
    }

    @Override
    public List<Patient> getAllPatients() {
        return patientRepository.findAll();
    }

    @Override
    public Patient getPatientById(Long id) {
        return patientRepository.findById(id).orElse(null);
    }

    @Override
    public void deletePatient(Long id) {
        patientRepository.deleteById(id);
    }
}
